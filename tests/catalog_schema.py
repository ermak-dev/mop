def main():
    try:
        import django
    except ImportError:
        hermetic.skip('catalogue schema', 'declared server extra is not installed')
        return
    from django.conf import settings
    settings.configure(INSTALLED_APPS=['mop.server.controller', 'mop.server.catalog'],
                       DATABASES={}, DEFAULT_AUTO_FIELD='django.db.models.BigAutoField')
    import django
    django.setup()
    from django.apps import apps
    from django.db.migrations.loader import MigrationLoader
    from django.db.migrations.state import ProjectState
    from django.db.migrations.autodetector import MigrationAutodetector
    from django.db.migrations.questioner import NonInteractiveMigrationQuestioner
    loader = MigrationLoader(None)
    changes = MigrationAutodetector(loader.project_state(), ProjectState.from_apps(apps),
        NonInteractiveMigrationQuestioner()).changes(graph=loader.graph)
    assert not changes, f'Catalogue models require migrations: {changes}'
    permission_registration_contract()
    protection_reauthorizes_after_external_wait()


# BUG: custom action names не создают назначаемых Django Permission.
# HYPOTHESIS: Meta.permissions отсутствуют, а limit скрыт за change_project.
CUSTOM_PERMISSIONS = {
    'project': {'configure_project', 'set_project_limit'},
    'node': {'configure_node', 'record_node_application', 'observe_node'},
    'installationconfiguration': {'record_settings_application'},
    'projectpolicysnapshot': {'pin_project_policy'},
}


def declared_permissions():
    from django.apps import apps
    result = set()
    for model in apps.get_app_config('catalog').get_models():
        opts = model._meta
        defaults = {f'{verb}_{opts.model_name}' for verb in opts.default_permissions}
        custom = {code for code, _ in opts.permissions}
        assert not defaults & custom, f'duplicate autogenerated permissions: {opts.label}'
        assert len(custom) == len(opts.permissions), f'duplicate custom permissions: {opts.label}'
        assert custom == CUSTOM_PERMISSIONS.get(opts.model_name, set()), (
            f'{opts.label} custom permissions: expected '
            f'{CUSTOM_PERMISSIONS.get(opts.model_name, set())}, got {custom}')
        result.update('catalog.' + code for code in defaults | custom)
    return result


def permission_registration_contract():
    import ast
    import importlib.util
    from mop.server.catalog import services
    declared = declared_permissions()
    module = 'mop.server.catalog.permissions'
    assert importlib.util.find_spec(module) is not None, 'missing catalog action-to-Django-permissions mapping'
    from mop.server.catalog.permissions import ACTION_PERMISSIONS
    tree = ast.parse(Path(services.__file__).read_text())
    emitted = {node.args[1].value for node in ast.walk(tree)
               if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
               and node.func.attr == '_authorize' and len(node.args) > 1
               and isinstance(node.args[1], ast.Constant)}
    assert set(ACTION_PERMISSIONS) == emitted, 'catalog mapping must cover exactly the emitted service actions'
    for action, required in ACTION_PERMISSIONS.items():
        assert type(required) is tuple and required, f'nonfinite permission requirements: {action}'
        assert len(required) == len(set(required)), f'duplicate requirements: {action}'
        assert set(required) <= declared, f'unregistered permissions for {action}: {set(required) - declared}'
        expected = (action,)
        if action in ('catalog.add_project', 'catalog.change_project', 'catalog.delete_project'):
            expected = (action, 'catalog.configure_project')
        elif action == 'catalog.set_project_limit':
            expected = ('catalog.change_project', 'catalog.configure_project', 'catalog.set_project_limit')
        elif action in ('catalog.add_node', 'catalog.change_node', 'catalog.delete_node', 'catalog.change_nodesetting'):
            expected = (action, 'catalog.configure_node')
        assert required == expected, f'wrong Django requirements for {action}: {required}'
    try:
        ACTION_PERMISSIONS['catalog.change_project'] = ('catalog.build_project',)
    except TypeError:
        pass
    else:
        raise AssertionError('catalog action mapping must be immutable')
    assert 'catalog.set_project_limit' in emitted, 'limit still indistinguishable from origin configuration'


def protection_reauthorizes_after_external_wait():
    # HYPOTHESIS: decrypt может ждать provider; прежний scope к возврату устареет.
    import hashlib
    import uuid
    from unittest.mock import patch
    from mop.server.catalog.models import ProjectPolicySnapshot
    from mop.server.catalog.services import Catalog
    from django.db import connection
    class Authority:
        revoked = False
        def authorize(self, *args, **kwargs):
            if self.revoked:
                raise PermissionError('scope revoked while waiting')
    authority = Authority()
    class Protector:
        def reveal(self, ciphertext, **kwargs):
            assert not connection.in_atomic_block, 'external protection runs inside SQL transaction'
            authority.revoked = True
            return b'private bytes'
    row = ProjectPolicySnapshot(project_id=uuid.uuid4(), sequence=1,
        content=b'ciphertext', confidential=True, protection_reference='secret:version',
        digest=hashlib.sha256(b'private bytes').hexdigest(), source_commit='a'*40,
        source_ref='main', provenance='test', cpu=100, memory_mb=256, disk_mb=1024)
    api = Catalog(authorizer=authority, protection=Protector())
    with patch.object(ProjectPolicySnapshot.objects, 'get', return_value=row):
        try:
            api.get_policy('trusted-actor', row.id)
        except PermissionError:
            pass
        else:
            raise AssertionError('private policy disclosed after scope revocation during protection I/O')
        authority.revoked = False
        with patch.object(connection, 'in_atomic_block', True):
            try:
                api.get_policy('trusted-actor', row.id)
            except RuntimeError as error:
                assert 'outside' in str(error)
            else:
                raise AssertionError('protection provider was allowed under an outer SQL transaction')


