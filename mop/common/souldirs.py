"""Корни каталога ролей (#603): одна таблица для клиента и сервера.

Роли живут в пакете (skills/<роль>/, #580) и внешних каталогах установки;
без общего места клиент (#586) собирал бы свою таблицу корней, сервер
(#581) свою, и расхождение означало бы: роль, которую CLI запускает,
сервер не находит, и наоборот. Общий модуль #580 фонов каталога не держит:
путь пакета и приоритет корней -- транспортная штука, не душа роли.
"""
import os

from . import config

# Каталог ролей пакета (#580): mop/skills/ внутри пакета, рядом с
# common/. Роли пакета едут с кодом всюду, где он есть; каталог skills/
# репозитория -- для установки, а не для клиента (#351, упаковка #580).
PACKAGE_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.realpath(__file__))),
    "skills")

# Настройка внешних каталогов установки (#603): список через os.pathsep
# (переносимо между unix и Windows-пользователями pip), доверенные внешние
# раньше, порядок -- старшинство (soul.catalogue берёт первого хозяина
# имени). Пусто -- только каталог пакета; своя таблица корней у клиента
# или сервера -- запретная копия этой таблицы.
ROOTS_SETTING = "MOP_SOUL_DIRS"


def roots():
    """Каталоги ролей по старшинству -> [путь, ...]. Чистая по данным.

    Внешние корни настройки раньше пакетного: каталог установки знает про
    роли больше пакета, и его роль не должна молча теряться за пакетной
    ролью того же имени. Пустые элементы настройки -- пропущены, не
    ошибка."""
    external = [d for d in (config.get(ROOTS_SETTING) or "").split(os.pathsep)
                if d]
    return external + [PACKAGE_DIR]
