"""Где mop держит своё на машине: ~/.config/mop и пути рядом с ним (#268).

Каталог был набран руками в двадцати местах, и путь к одному и тому же
файлу выглядел по-разному: expanduser, f-строка от дома пула, «~/» для
разворота позже. Здесь одно написание; остальные модули собирают свои пути
отсюда.

Два дома. local() -- дом этого процесса: оператор, сервер, агент на своём
узле. under(home) -- чужой дом: дом пула в теле (MOP_HOME, driver.HOME),
который знает не этот процесс, а спека. Врапер спеки (spec.WRAPPER) пишет
путь сам, строкой: он едет в тело текстом, и его правка -- перерегистрация
всего пула.

Только stdlib и без импортов из пакета: модуль читают и busnames, и config,
которые стоят в самом низу.
"""
import os

DIR = ".config/mop"                          # от дома, своего или чужого

# Пути рядом с каталогом: одно имя на файл, чтобы свой и чужой дом не
# разошлись в написании.
SECRETS = "secrets"                          # пароли и ключи контроллера
SECRETS_ENV = "secrets.env"                  # ключи LLM на узле и в теле
SERVERS = "servers"                          # креды серверов у оператора
BOOTSTRAP = "bootstrap"                      # файлы bootstrap'а у сервера
PROJECTS = "projects"                        # реестр проектов сервера
NODE_ENV = "node.env"                        # что узел знает о себе


def local(*parts):
    """Путь в ~/.config/mop этого процесса. Дом -- на момент вызова, как у
    expanduser, который здесь стоял: модули, берущие путь при импорте, берут
    его при импорте, а зовущие по ходу -- по ходу."""
    return os.path.join(os.path.expanduser(f"~/{DIR}"), *parts)


def under(home, *parts):
    """Путь в .config/mop чужого дома (дом пула в теле, на узле)."""
    return os.path.join(home, DIR, *parts)
