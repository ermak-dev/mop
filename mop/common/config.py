class Missing(RuntimeError):
    """Обязательная настройка не заполнена."""


def require(*names):
    """Проверить обязательные — все, либо названные. Зовут фронтенды перед
    работой с кластером: мастеру нужен один MOP_SERVER_LAN, MOP_GIT_HOST
    читают только плейбуки, и требовать его на машине оператора значит
    заставлять вписывать то, чем она не пользуется.

    Отказ громкий и с перечнем: молча взять чужой дефолт и пойти в чужую
    локалку — худшее, что может сделать инструмент на новой машине."""
    gaps = [f"  {k} — {why}" for k, why in REQUIRED.items()
            if (not names or k in names) and not get(k, "")]
    if gaps:
        raise Missing("required settings not filled in " + ENV_FILE
                      + ":\n" + "\n".join(gaps)
                      + "\n\ntemplate: cp .env.example .env")

_cache = {}


def read_env(path):
    """То же файлом. Отсутствие файла — штатный случай: на узле нет .env, на
    управляющей машине нет node.env. Публична, потому что тем же форматом
    читаются и ключи LLM из .env (keys.llm_keys_blob)."""
    try:
        with open(path) as f:
            return fsutil.read_kv(f.read())
    except OSError:
        return {}


def _file(path):
    """Файл настроек, прочитанный один раз за процесс."""
    if path not in _cache:
        _cache[path] = read_env(path)
    return _cache[path]


# Поля контекста команды (#131, mop/common/context.py): их значение, если контекст
# его задал, старше файлов. Контекст уже учёл клон, окружение и командную
# строку в своём порядке.
#
# Объявляет их context (FIELDS) и сам вписывает сюда при импорте (#156):
# config -- нижний слой и сверху не читает ничего, а обратная копия полей
# однажды разошлась бы с оригиналом. Пока context не импортирован,
# контекста нет и быть не может: use() живёт там же.
CONTEXT_SCOPED = {}
_context_now = None


def attach_context(scoped, now):
    """{переменная: поле контекста}, функция текущего контекста. Зовёт
    context при импорте; поля, не являющиеся настройками, не берутся."""
    global _context_now
    CONTEXT_SCOPED.update({v: f for v, f in scoped.items() if v in SETTINGS})
    _context_now = now


def _context(name):
    if name not in CONTEXT_SCOPED or _context_now is None:
        return None
    return getattr(_context_now(), CONTEXT_SCOPED[name])


def _load():
    """Настройки установки: .env рядом с кодом."""
    return _file(ENV_FILE)


def _node():
    """Настройки этого узла: node.env, положенный прогоном deploy."""
    return _file(NODE_ENV_FILE)


def forget():
    """Забыть прочитанное. Нужно проверкам, которые подсовывают свои файлы;
    в работе файлы читаются один раз за процесс и меняться не могут."""
    _cache.clear()


def get(name, default=None):
    """Значение настройки: контекст команды (#131, только CONTEXT_SCOPED) >
    окружение > node.env > .env > дефолт из SETTINGS.

    Дефолт не передаётся вызывающим. Пока передавался, каждая точка вызова
    несла свою копию — и копии пережили превращение SETTINGS в источник
    правды: зашитый в точке вызова дефолт `NOMAD_ADDR` продолжал
    отдавать адрес автора там, где REQUIRED уже требовал заполнить его руками.
    Настройка описана в одном месте или ни в одном."""
    if default is None:
        default = SETTINGS.get(name, "")
    if name in PROCESS_SCOPED:
        return os.environ.get(name) or default
    value = (_context(name) or os.environ.get(name)
             or _node().get(name) or _load().get(name))
    if value:
        return value
    return DERIVED[name]() if not default and name in DERIVED else default


def effective():
    """Все настройки с учётом .env и окружения. -> {имя: (значение, откуда)}."""
    out = {}
    for name, default in SETTINGS.items():
        if _context(name):
            out[name] = (_context(name), _context_now().sources.get(
                CONTEXT_SCOPED[name], "context"))
        elif os.environ.get(name):
            out[name] = (os.environ[name], "env")
        elif name in PROCESS_SCOPED:
            out[name] = (default, "default")
        elif _node().get(name):
            out[name] = (_node()[name], "node")
        elif _load().get(name):
            out[name] = (_load()[name], ".env")
        elif name in DERIVED:
            out[name] = (DERIVED[name](), "derived")
        else:
            out[name] = (default, "default")
    return out


def num(name, default=None):
    try:
        return int(get(name, default))
    except ValueError:
        return int(default if default is not None else SETTINGS[name])
