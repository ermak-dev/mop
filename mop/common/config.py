def pool_user():
    """Под кем идут задачи пула, когда настройка не задана.

    По uid процесса, а не по $USER. Переменная — утверждение, uid — факт, и
    расходятся они не в теории: внешний врапер исполняется задачей Nomad, а
    клиент Nomad крутится под root и свой $USER задаче отдаёт. Пока дефолт
    верил переменной, драйвер контейнеров собирал `ssh root@<тело>` и получал
    отказ по ключу — при совершенно исправном ключе и правильном пользователе
    внутри. Проверка в tests/config.py."""
    try:
        return pwd.getpwuid(os.getuid()).pw_name
    except KeyError:
        # uid без записи в passwd бывает в контейнере с чужим /etc/passwd;
        # тогда переменная — единственное, что есть.
        return os.environ.get("USER") or "root"

