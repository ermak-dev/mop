SHARD_SCOPED = (
    "MOP_PUPPET_MEM_MAX_MB",
    "MOP_PVE_DISK_GB",
    "MOP_PVE_CORES",
)


def shard_settings(text):
    """Содержимое `.mop` -> ({разрешённое}, [отброшенные ключи]).

    Отброшенное возвращается, а не молчит: проглоченный ключ — это либо
    настройка, которая не сработала, либо чужая, которая сработала. И то и
    другое обязано быть видно тому, кто собирает образ."""
    good, bad = {}, []
    for k, v in _parse(text).items():
        (good.__setitem__(k, v) if k in SHARD_SCOPED else bad.append(k))
    return good, bad


class Missing(RuntimeError):
    """Обязательная настройка не заполнена."""


def require():
    """Проверить обязательные. Зовут фронтенды перед работой с кластером.

    Отказ громкий и с перечнем: молча взять чужой дефолт и пойти в чужую
    локалку — худшее, что может сделать инструмент на новой машине."""
    gaps = [f"  {k} — {why}" for k, why in REQUIRED.items() if not get(k, "")]
    if gaps:
        raise Missing("required settings not filled in " + ENV_FILE
                      + ":\n" + "\n".join(gaps)
                      + "\n\ntemplate: cp .env.example .env")

_cache = {}


def _parse(text):
    """Текст вида КЛЮЧ=значение -> dict. Формат намеренно примитивен: его
    читают и питон, и ansible, и sed."""
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        k, sep, v = line.partition("=")
        if sep:
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def _read(path):
    """То же файлом. Отсутствие файла — штатный случай: на узле нет .env, на
    управляющей машине нет node.env, у проекта может не быть .mop."""
    try:
        with open(path) as f:
            return _parse(f.read())
    except OSError:
        return {}


def _load():
    """Настройки установки: .env рядом с кодом."""
    if ENV_FILE not in _cache:
        _cache[ENV_FILE] = _read(ENV_FILE)
    return _cache[ENV_FILE]


def _node():
    """Настройки ЭТОГО УЗЛА: node.env, положенный прогоном deploy."""
    if NODE_ENV_FILE not in _cache:
        _cache[NODE_ENV_FILE] = _read(NODE_ENV_FILE)
    return _cache[NODE_ENV_FILE]


def forget():
    """Забыть прочитанное. Нужно проверкам, которые подсовывают свои файлы;
    в работе файлы читаются один раз за процесс и меняться не могут."""
    _cache.clear()


def get(name, default=None):
    """Значение настройки: окружение > .env > дефолт из SETTINGS.

    Дефолт НЕ передаётся вызывающим. Пока передавался, каждая точка вызова
    несла свою копию — и копии пережили превращение SETTINGS в источник
    правды: зашитый в точке вызова дефолт `NOMAD_ADDR` продолжал
    отдавать адрес автора там, где REQUIRED уже требовал заполнить его руками.
    Настройка описана в одном месте или ни в одном."""
    if default is None:
        default = SETTINGS.get(name, "")
    value = os.environ.get(name) or _node().get(name) or _load().get(name)
    if value:
        return value
    return DERIVED[name]() if not default and name in DERIVED else default


def effective():
    """Все настройки с учётом .env и окружения. -> {ИМЯ: (значение, откуда)}."""
    out = {}
    for name, default in SETTINGS.items():
        if os.environ.get(name):
            out[name] = (os.environ[name], "env")
        elif _node().get(name):
            out[name] = (_node()[name], "node")
        elif _load().get(name):
            out[name] = (_load()[name], ".env")
        elif name in DERIVED:
            out[name] = (DERIVED[name](), "derived")
        else:
            out[name] = (default, "default")
    return out


def num(name, default=None):
    try:
        return int(get(name, default))
    except ValueError:
        return int(default if default is not None else SETTINGS[name])
