// Словарь меток GUI (#521): одна буква решает -- метки кнопок и пунктов
// пишутся с заглавной, тексты и подписи -- как предложит фраза. Прежде
// кнопки были строчными («выполнить», «назад», «отмена»), а вход/выход --
// латиницей (Login/Logout). Словарь живёт в components/labels.ts,
// компоненты его читают -- источник один, как у KIND_WORD (#323).
// Имена recycle/delete/wipe утверждены оператором: Пересоздать/Удалить/
// Сбросить («Очистить» читается про место, а не про состояние). Ключи
// словаря остались серверными -- снаружи видны только русские слова.
//
// HYPOTHESIS: метки разбросаны по компонентам строками; без словаря
// следующий экран родит ещё одну копию «Отмена».
// SOLUTION: LABELS в components/labels.ts, красные проверки ниже.
import { expect, test } from "vitest";
import { LABELS } from "./labels";

test("#521 the label dictionary carries the operator's words, capitalized", () => {
  // Ядро диспатча: с заглавной, русские, без латиницы Login/Logout
  expect(LABELS).toMatchObject({
    login: "Войти", logout: "Выйти",
    cancel: "Отмена", back: "Назад", next: "Далее",
    run: "Выполнить", confirm: "Подтвердить",
    close: "Закрыть", again: "Новая команда",
    // пункты визарда #520: шесть действий с заглавной; разрушительные --
    // русские имена, утверждены оператором в приёмке #521
    update: "Обновление", model: "Модель", restart: "Рестарт",
    recycle: "Пересоздать", delete: "Удалить", wipe: "Сбросить",
    // хвост экрана (#489) и действия строки
    refresh: "Обновить", screen: "Экран", edit: "Правка",
    send: "Отправить",
  });
});

test("#521 no latin button word survives in the dictionary", () => {
  // Login/Logout должны быть заменены русскими словами
  expect(Object.values(LABELS)).not.toContain("Login");
  expect(Object.values(LABELS)).not.toContain("Logout");
});

// Тексты последствий (#521): литературный русский в стиле оператора --
// простые утверждения «что гибнет, что живёт», без путей и имён команд.
// Образец -- wipe у #473: «Клон будет сброшен к HEAD, каталог цели
// вычищен. Тело пересоздаётся, разговор теряется.» Словари последствий
// живут у движков (PREVIEW/MODES), проверяем их строки.
import { PREVIEW } from "./DestructiveBox";
import { MODES } from "./UpdateBox";

test("#521 the destructive consequences read like the operator's wipe sample", () => {
  // wipe -- эталон диспатча, слово в слово
  expect(PREVIEW.wipe.lines).toEqual([
    "Клон будет сброшен к HEAD, каталог цели вычищен.",
    "Тело пересоздаётся, разговор теряется.",
    "Живая сессия — отказ: wipe для остановленного, полный цикл — recycle.",
  ]);
  // delete: что гибнет, что остаётся
  expect(PREVIEW.delete.lines).toEqual([
    "Клон и джоб удаляются, папета больше нет.",
    "Тело — контейнер: уйдут память и диск вместе с ним.",
  ]);
  // recycle: клон начисто, тело живёт
  expect(PREVIEW.recycle.lines).toEqual([
    "Клон будет возвращён к origin/ветке: несохранённая работа погибнет.",
    "Каталог цели будет вычищен целиком: первая сборка после recycle медленная.",
    "Джоб и тело останутся жить: папет поднимется заново на чистом клоне.",
  ]);
});

test("#521 the update mode consequences read in the same voice", () => {
  expect(MODES.keep.lines).toEqual([
    "Разговор продолжится: контекст сессии остаётся.",
    "Несохранённая работа в клоне не трогается: ничего не гибнет.",
  ]);
  expect(MODES.replace.lines).toEqual([
    "Клон будет пересобран начисто: несохранённая работа погибнет.",
    "Разговор погибнет: сессия начнётся с нуля.",
  ]);
  expect(MODES.remove.lines).toEqual([
    "Клон будет пересобран от нового origin: несохранённая работа погибнет.",
    "Разговор погибнет: сессия начнётся с нуля.",
    "Папет продолжит жить под тем же именем.",
  ]);
});

// Рестарт: у действия нет шага параметров, но его последствия входят в
// диспатч -- визард показывает их на первом экране подсказкой? Нет:
// рестарт шлёт POST сразу (#513), текст последствий живёт в словаре
// RESTART_EFFECTS и показывается там, где спросит дизайн. Проверяем
// факт: словарь существует и звучит тем же голосом.
import { RESTART_EFFECTS } from "./RestartBox";

test("#521 the restart consequences are named in the same voice", () => {
  expect(RESTART_EFFECTS).toEqual([
    "Клон не трогается: несохранённая работа живёт.",
    "Разговор теряется: сессия поднимается заново.",
  ]);
});
