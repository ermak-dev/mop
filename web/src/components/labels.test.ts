// Словарь меток GUI (#521): одна буква решает -- метки кнопок и пунктов
// пишутся с заглавной, тексты и подписи -- как предложит фраза. Прежде
// кнопки были строчными («выполнить», «назад», «отмена»), а вход/выход --
// латиницей (Login/Logout). Словарь живёт в components/labels.ts,
// компоненты его читают -- источник один, как у KIND_WORD (#323).
// Имена recycle/delete/wipe утверждены оператором: Пересоздать/Удалить/
// Сбросить («Очистить» читается про место, а не про состояние). Ключи
// словаря остались серверными -- снаружи видны только русские слова.
//
// HYPOTHESIS: метки разбросаны по компонентам строками; без словаря
// следующий экран родит ещё одну копию «Отмена».
// SOLUTION: LABELS в components/labels.ts, красные проверки ниже.
import { expect, test } from "vitest";
import { LABELS } from "./labels";

test("#521 the label dictionary carries the operator's words, capitalized", () => {
  // Ядро диспатча: с заглавной, русские, без латиницы Login/Logout
  expect(LABELS).toMatchObject({
    login: "Войти", logout: "Выйти",
    cancel: "Отмена", back: "Назад",
    // футер визарда #522: одна кнопка согласия у всех операций --
    // «Продолжить» ведёт к финалу, «Завершить» его исполняет; «Выполнить»
    // и «Подтвердить» ушли вместе с режимами подтверждения
    next: "Продолжить", finish: "Завершить",
    close: "Закрыть", again: "Новая команда",
    // пункты визарда #520: шесть действий с заглавной; разрушительные --
    // русские имена, утверждены оператором в приёмке #521
    update: "Обновление", model: "Модель", restart: "Рестарт",
    recycle: "Пересоздать", delete: "Удалить", wipe: "Сбросить",
    // хвост экрана (#489) и действия строки
    refresh: "Обновить", screen: "Экран", edit: "Правка",
    send: "Отправить",
  });
});

test("#521 no latin button word survives in the dictionary", () => {
  // Login/Logout должны быть заменены русскими словами
  expect(Object.values(LABELS)).not.toContain("Login");
  expect(Object.values(LABELS)).not.toContain("Logout");
});

test("#522 the wizard footer words replace the per-mode buttons", () => {
  // единое правило подтверждения #522: «Выполнить»/«Подтвердить» ушли,
  // осталась пара «Продолжить»/«Завершить»
  expect(Object.values(LABELS)).not.toContain("Выполнить");
  expect(Object.values(LABELS)).not.toContain("Подтвердить");
  expect(Object.values(LABELS)).not.toContain("Далее");
});

// Тексты последствий (#521): литературный русский в стиле оператора --
// простые утверждения «что гибнет, что живёт», без путей и имён команд.
// Образец -- wipe у #473: «Клон будет сброшен к HEAD, каталог цели
// вычищен. Тело пересоздаётся, разговор теряется.» Словари последствий
// живут у движков (PREVIEW/MODES), проверяем их строки.
// #527: словарь замен терминов по телу тикета -- origin→репозиторий,
// клон→рабочая копия, разговор/сессия→контекст диалога с Claude,
// пересадка→переключение на другой проект, джоб→задача. Строки ниже --
// канон из тикета; оные слова ушли из последствий всех потоков.
import { PREVIEW } from "./DestructiveBox";
import { MODES } from "./UpdateBox";
import { RESTART_EFFECTS } from "./RestartBox";

// Слова, которых #527 в последствиях больше не держит: замена -- весь
// словарь ниже. «сила (force) не применяется» ушла вовсе, «частичный
// исход…» упрощена (жила в ControlWindow, не в словарях -- проверяется
// экранными тестами).
const GONE = [
  /\borigin\b/i, /\bклон\b/i, /\bразговор\b/i, /\bджоб\b/i,
  /\bпересад/i, /сила \(force\)/i,
];

test("#527 no pre-refactor term survives in the effect dictionaries", () => {
  const all = [...PREVIEW.recycle.lines, ...PREVIEW.delete.lines,
    ...PREVIEW.wipe.lines, ...MODES.keep.lines, ...MODES.replace.lines,
    ...MODES.remove.lines, ...RESTART_EFFECTS];
  for (const line of all) {
    for (const gone of GONE) {
      expect(line, `«${line}» держит ушедший термин (${gone})`)
        .not.toMatch(gone);
    }
  }
});

test("#521 the destructive consequences read like the operator's wipe sample", () => {
  // #527: тот же голос, словарь замен применён (джоб→задача, клон→
  // рабочая копия, разговор→контекст диалога); «HEAD» в wipe остался --
  // это технический факт цели, не термин замены
  expect(PREVIEW.wipe.lines).toEqual([
    "Рабочая копия будет сброшена к HEAD, каталог цели вычищен.",
    "Тело пересоздаётся, контекст диалога с Claude теряется.",
    "Живая сессия — отказ: сброс — для остановленного, полный цикл — пересоздание.",
  ]);
  // delete: что гибнет, что остаётся
  expect(PREVIEW.delete.lines).toEqual([
    "Рабочая копия и задача удаляются, папета больше нет.",
    "Тело — контейнер: уйдут память и диск вместе с ним.",
  ]);
  // recycle: рабочая копия начисто, тело живёт
  expect(PREVIEW.recycle.lines).toEqual([
    "Рабочая копия будет возвращена к репозиторию и ветке: несохранённая работа погибнет.",
    "Каталог цели будет вычищен целиком: первая сборка после пересоздания медленная.",
    "Задача и тело останутся жить: папет поднимется заново на чистой рабочей копии.",
  ]);
});

test("#521 the update mode consequences read in the same voice", () => {
  // #527: разговор→контекст диалога, клон→рабочая копия, origin→
  // репозиторий, пересадка→переключение на другой проект
  expect(MODES.keep.lines).toEqual([
    "Контекст диалога с Claude сохранится: сессия продолжится.",
    "Несохранённая работа в рабочей копии не трогается: ничего не гибнет.",
  ]);
  expect(MODES.replace.lines).toEqual([
    "Рабочая копия будет пересобрана начисто: несохранённая работа погибнет.",
    "Контекст диалога с Claude погибнет: сессия начнётся с нуля.",
  ]);
  expect(MODES.remove.lines).toEqual([
    "Рабочая копия будет пересобрана от нового репозитория: несохранённая работа погибнет.",
    "Контекст диалога с Claude погибнет: сессия начнётся с нуля.",
    "Папет продолжит жить под тем же именем.",
  ]);
});

// Рестарт: у действия нет шага параметров, но его последствия входят в
// диспатч -- визард показывает их на финальном экране. Словарь
// RESTART_EFFECTS звучит тем же голосом, слова -- словарь #527.
test("#521 the restart consequences are named in the same voice", () => {
  expect(RESTART_EFFECTS).toEqual([
    "Рабочая копия не трогается: несохранённая работа живёт.",
    "Контекст диалога с Claude теряется: сессия поднимается заново.",
  ]);
});
