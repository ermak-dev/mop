// Числа расхода как на прежней странице (#299): 171M, 35M, 2.9k. Тот же
// порог, что у `human` старого скрипта -- меньше десяти единиц с одним
// знаком, дальше целым. Свой файл, а не общий format.ts: его заводит #298,
// и две ветки не должны спорить за одно место.

export function human(n: number): string {
  for (const [unit, div] of [["G", 1e9], ["M", 1e6], ["k", 1e3]] as const) {
    if (n >= div) {
      const v = n / div;
      return (v < 10 ? v.toFixed(1) : v.toFixed(0)) + unit;
    }
  }
  return String(n);
}

// Склонение дней для подписи «за N дней»: та же таблица, что у старой
// страницы, без обращения к App (App импортирует компоненты, и обратная
// зависимость сделала бы круг).
export function pluralDays(n: number): string {
  const m100 = n % 100, m10 = n % 10;
  const word = m100 > 10 && m100 < 20 ? "дней" : m10 === 1 ? "день" : m10 > 1 && m10 < 5 ? "дня" : "дней";
  return `${n} ${word}`;
}
